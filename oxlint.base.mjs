// oxlint の設定を返す。prettier と重なる書式のルールは有効にしない。
export function createConfig({
  environment,
  testFiles = ["tests/**/*.test.ts"],
}) {
  if (environment !== "node" && environment !== "browser") {
    throw new Error("Choose node or browser for the oxlint environment.");
  }
  const sourceFiles = ["**/*.{js,mjs,cjs,ts,tsx,mts,cts}"];
  const nodeFiles = [
    "*.config.{js,mjs,cjs,ts,tsx,mts,cts}",
    "tests/**/*.{js,mjs,cjs,ts,tsx,mts,cts}",
    "src/**/*.{test,spec}.{js,mjs,cjs,ts,tsx,mts,cts}",
    "src/**/__tests__/**/*.{js,mjs,cjs,ts,tsx,mts,cts}",
  ];
  const browserOnly = Object.keys(globals.browser).filter(
    (name) => !(name in globals.node),
  );
  return {
    plugins: ["typescript", "vitest"],
    // 既定で入る correctness の組みは使わず、下に書いたルールだけを有効にする。
    categories: { correctness: "off" },
    options: { typeAware: true, reportUnusedDisableDirectives: "error" },
    ignorePatterns: [
      "node_modules/**",
      "dist/**",
      "coverage/**",
      ".tools/**",
      ".husky/_/**",
    ],
    overrides: [
      { files: ["**/*.{js,mjs,cjs}"], rules: recommended },
      {
        files: ["**/*.{ts,tsx,mts,cts}"],
        rules: { ...recommended, ...typescriptBase, ...typescriptStrict },
      },
      {
        files: sourceFiles,
        jsPlugins: ["eslint-plugin-regexp"],
        rules: regexp.configs["flat/recommended"].rules,
      },
      {
        files: ["**/*.{js,mjs,cjs}"],
        excludeFiles: ["src/**"],
        env: { node: true },
      },
      {
        files: ["src/**/*.{js,mjs,cjs,ts,tsx,mts,cts}"],
        excludeFiles: nodeFiles,
        env: environment === "browser" ? { browser: true } : { node: true },
      },
      {
        files: nodeFiles,
        env: { node: true },
        rules: {
          "no-restricted-globals": [
            "error",
            { globals: browserOnly, checkGlobalObject: true },
          ],
        },
      },
      {
        files: environment === "node" ? sourceFiles : nodeFiles,
        jsPlugins: ["eslint-plugin-n"],
        rules: {
          "n/no-unsupported-features/node-builtins": [
            "error",
            { allowExperimental: false },
          ],
        },
      },
      { files: testFiles, rules: vitestRules },
      {
        files: [
          "src/**/*.{js,mjs,cjs,ts,tsx,mts,cts}",
          "tests/**/*.{js,mjs,cjs,ts,tsx,mts,cts}",
        ],
        rules: {
          complexity: ["error", { max: 10, variant: "classic" }],
          "max-lines-per-function": [
            "error",
            { max: 50, skipBlankLines: true, skipComments: true, IIFEs: true },
          ],
          "max-depth": ["error", 3],
        },
      },
    ],
  };
}
